CREATE TABLE ranks (
    rank_id INTEGER PRIMARY KEY,
    rank_name VARCHAR(50) NOT NULL UNIQUE,
    rank_level INTEGER NOT NULL CHECK (rank_level BETWEEN 1 AND 6)
);

CREATE TABLE units (
    unit_id INTEGER PRIMARY KEY,
    unit_name VARCHAR(100) NOT NULL UNIQUE,
    locations VARCHAR(100) NOT NULL
);

CREATE TABLE missions (
    mission_id INTEGER PRIMARY KEY,
    mission_name VARCHAR(100) NOT NULL UNIQUE,
    start_date DATE NOT NULL,
    end_date DATE,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE soldiers (
    soldier_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_no VARCHAR(50) NOT NULL UNIQUE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    date_of_birth DATE NOT NULL,
    enlistment_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'On Leave', 'Retired')),
    rank_id INTEGER NOT NULL REFERENCES ranks(rank_id),
    unit_id INTEGER NOT NULL REFERENCES units(unit_id),
    CHECK (enlistment_date > date_of_birth)
);

CREATE TABLE soldier_mission (
    soldier_id INTEGER NOT NULL REFERENCES soldiers(soldier_id),
    mission_id INTEGER NOT NULL REFERENCES missions(mission_id),
    mission_role VARCHAR(100) NOT NULL,
    PRIMARY KEY (soldier_id, mission_id)
);


